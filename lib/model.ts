// The token radar's model ("radar-2"): one snapshot of the protocol universe in,
// one ranked board out.
//
// The board ranks every protocol that records no token and is not a wrapped,
// staked or bridged product of one that trades, and is not an exchange or a
// versioned pool. The snapshot's watchlist is the floor: every slug on it is
// ranked, and the radar adds every other protocol that meets the same rule
// below the watchlist floor. A protocol is pre-token when its record carries
// no market cap, no CoinGecko id and no symbol; the snapshot's live-token
// protocols are kept apart and shown with the market's own values, never
// mixed into the ranked board.
//
// Implied value is anchored in what the market already pays for the same kind
// of protocol, then adjusted by the protocol's own record:
//
//   comps    = median(mcap_usd / tvl_usd) over the live-token protocols in the
//              protocol's own category (at least 3 of them, else the global
//              median over all live-token protocols), clamped to [0.05, 2.0]
//   base     = tvl_usd x comps
//   growth   = clamp(change_7d, -50, 100) per cent
//   growthMult   = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity = 0.7 + min(age_days, 1095) / 1095 x 0.3   (age unknown: 365 days)
//   chains   = 1 + 0.05 x min(chains - 1, 4)
//   implied  = max(1, round(base x growthMult x maturity x chains))
//
// No protocol name is ever special-cased: the same function scores every row.
// The constants are stated in the dashboard, and the dashboard's sandbox lets
// a reader change the three weights and watch the board re-rank.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

